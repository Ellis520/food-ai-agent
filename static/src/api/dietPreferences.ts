export function findDietConflicts(...fields: string[]) {
  const choices = new Set(
    fields.flatMap((value) =>
      value
        .normalize("NFKC")
        .split(/[、,，;；/\n]+/)
        .map((part) => part.trim())
        .filter(Boolean),
    ),
  );
  return conflictingChoices.flatMap(([first, second]) => {
    const a = first.find((choice) => choices.has(choice));
    const b = second.find((choice) => choices.has(choice));
    return a && b ? [`「${a}」与「${b}」可能冲突`] : [];
  });
}

