import {test,expect} from '../completeProfile'

test('提示分类、输入问题、失败重试、上下文追问与页面清空',async({page})=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
 const requests:{message:string;history:{role:string;text:string}[]}[]=[]
 await page.route('**/api/safety/ask',async route=>{
  requests.push(route.request().postDataJSON())
  if(requests.length===1)return route.fulfill({status:502,json:{detail:'测试：服务暂不可用，请重试。'}})
  return route.fulfill({json:{source:'qwen-curated-safety',data:{answer:'测试模拟答复：熟食应及时冷藏，再吃前彻底加热。',steps:['核对已经放置的时间和保存环境。'],followUp:'已经放了多久？',sources:[{id:'who',title:'WHO · 食品安全五要点',url:'https://www.who.int/docs/default-source/wpro---documents/posters/food-safety/the-five-keys-to-safer-food-brochure.pdf'}],provider:'qwen',kind:'general',reviewedAt:'2026-11-03',note:'这是自动化测试的模拟答复。'}}})
 })
 await page.goto('/?v=safety-test#/language')
 await expect(page.locator('h1')).toContainText('饮食小贴士')
 await expect(page.locator('.safety-tip')).toHaveCount(5)
 await page.getByRole('button',{name:'储存与剩菜',exact:true}).click()
 await expect(page.locator('.safety-tip')).toHaveCount(1)
 await page.getByRole('button',{name:'问一问',exact:true}).click()
 await expect(page.getByRole('textbox',{name:'饮食安全问题',exact:true})).toHaveValue('外卖没吃完，怎么保存更安全？')
 expect(requests).toHaveLength(0)
 await page.getByRole('button',{name:'发送问题',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('服务暂不可用')
 await expect(page.getByRole('textbox',{name:'饮食安全问题',exact:true})).toHaveValue('外卖没吃完，怎么保存更安全？')
 await page.getByRole('button',{name:'重试这次问题',exact:true}).click()
 await expect(page.getByRole('article',{name:'安全问答回复'})).toContainText('测试模拟答复')
 await expect(page.getByRole('article',{name:'安全问答回复'}).getByRole('link',{name:/WHO/})).toHaveAttribute('href',/^https:\/\/www\.who\.int\//)
 await page.getByRole('textbox',{name:'饮食安全问题',exact:true}).fill('放了一个小时呢？')
 await page.getByRole('button',{name:'发送问题',exact:true}).click()
 await expect(page.getByRole('article',{name:'安全问答回复'})).toHaveCount(2)
 expect(requests[2].history).toHaveLength(2)
 expect(Object.keys(requests[2]).sort()).toEqual(['healthHistory','history','message'])
 await page.getByRole('button',{name:'清空本页问答',exact:true}).click()
 await expect(page.getByRole('article',{name:'安全问答回复'})).toHaveCount(0)
 await page.setViewportSize({width:390,height:844})
 await expect.poll(()=>page.locator('.sidebar').evaluate(el=>el.getBoundingClientRect().right)).toBeLessThanOrEqual(0)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.evaluate(()=>{(document.activeElement as HTMLElement)?.blur();scrollTo(0,0)})
 await page.screenshot({path:'../safety-mobile-preview.png',fullPage:true})
 expect(errors).toEqual([])
})

test('危险症状走真实本地提醒接口，不写入记录，离开页面清空',async({page})=>{
 await page.goto('/#/language')
 await expect(page.locator('h1')).toContainText('饮食小贴士')
 const before=(await (await page.request.get('/api/state')).json()).data
 await page.getByRole('textbox',{name:'饮食安全问题',exact:true}).fill('如果吃东西后呼吸困难怎么办？')
 await page.getByRole('button',{name:'发送问题',exact:true}).click()
 const reply=page.getByRole('region',{name:'紧急求助'})
 await expect(reply.getByRole('link',{name:/拨打 120/})).toHaveAttribute('href','tel:120')
 expect((await (await page.request.get('/api/state')).json()).data).toEqual(before)
 await page.goto('/#/nutrition');await expect(page.locator('.safety-chat')).toHaveCount(0)
 await page.goto('/#/language');await expect(reply).toHaveCount(0)
})

