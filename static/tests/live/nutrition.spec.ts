import {test,expect} from '../completeProfile'
import {readFile} from 'node:fs/promises'

test('自填营养表、示例组合、未知与0区分、SQLite恢复、编辑导出删除',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.setViewportSize({width:1440,height:1050});await page.goto('/?v=nutrition-test#/nutrition')
 await expect(page.getByRole('button',{name:'自填营养表',exact:true})).toBeVisible()
 const before=(await (await page.request.get('/api/state')).json()).data.state
 await page.getByRole('button',{name:'自填营养表',exact:true}).click()
 await page.getByLabel('食物名称',{exact:true}).fill('测试酸奶（自填）')
 await page.getByLabel('食用份量（g）',{exact:true}).fill('200')
 await page.getByLabel('包装能量单位').selectOption('kJ')
 for(const [label,value] of [['热量','418.4'],['蛋白质','4'],['碳水化合物','5'],['脂肪','2'],['钠','0']])await page.getByLabel('每100g'+label,{exact:true}).fill(value)
 await page.getByRole('button',{name:'添加自填食物',exact:true}).click()
 await expect(page.locator('[data-nutrient=kcal] strong')).toContainText('200')
 await expect(page.locator('[data-nutrient=fiber]')).toContainText('未提供数值')
 await expect(page.locator('[data-nutrient=sodium] strong')).toContainText('0')
 await page.getByRole('button',{name:'示例目录',exact:true}).click()
 await page.getByLabel('示例食物',{exact:true}).selectOption('egg')
 await page.getByLabel('添加份量（g）',{exact:true}).fill('100')
 await page.getByRole('button',{name:'添加示例食物',exact:false}).click()
 await expect(page.locator('[data-nutrient=kcal] strong')).toContainText('344')
 await expect(page.locator('[data-nutrient=protein] strong')).toContainText('21')
 await expect(page.locator('[data-nutrient=fiber]')).toContainText('仅已知部分')
  await page.getByLabel('分项指标',{exact:true}).selectOption('fiber')
  const breakdown=page.getByRole('region',{name:'食物营养贡献明细',exact:true})
  await expect(breakdown).toContainText('比例仅在已知数值中比较')
  await expect(breakdown.locator('.contribution-row').first()).toContainText('未知')
  await breakdown.getByText('查看每100g与份量换算明细',{exact:true}).click()
  await expect(breakdown.getByRole('table')).toContainText('未知')
  await page.getByLabel('分项指标',{exact:true}).selectOption('kcal')
 await page.getByLabel('搭配名称',{exact:true}).fill('测试组合早餐')
 await page.getByRole('button',{name:'保存搭配',exact:true}).click()
 await expect.poll(async()=>((await (await page.request.get('/api/state')).json()).data.state.nutritionRecipes||[]).length).toBe(1)
 let stored=(await (await page.request.get('/api/state')).json()).data.state
 expect(stored.nutritionRecipes[0].items[0].per100.fiber).toBeNull();expect(stored.meals).toEqual(before.meals)
 await page.reload();await page.getByRole('button',{name:'载入测试组合早餐',exact:true}).click()
 await expect(page.locator('.nutrition-entry')).toHaveCount(2)
 await page.evaluate(()=>{(document.activeElement as HTMLElement)?.blur();window.scrollTo(0,0)})
 await page.screenshot({path:'../nutrition-preview.png'})
 await page.setViewportSize({width:390,height:844})
 await expect.poll(()=>page.locator('.sidebar').evaluate(el=>el.getBoundingClientRect().right)).toBeLessThanOrEqual(0)
 await page.evaluate(()=>{(document.activeElement as HTMLElement)?.blur();window.scrollTo(0,0)})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:'../nutrition-mobile-preview.png'})
 await page.locator('.nutrition-calculation .nutrition-total-line').scrollIntoViewIfNeeded()
 await page.screenshot({path:'../nutrition-summary-mobile-preview.png'})
 await page.getByRole('spinbutton',{name:'测试酸奶（自填）份量（g）',exact:true}).fill('100')
 await expect(page.locator('[data-nutrient=kcal] strong')).toContainText('244')
 stored=(await (await page.request.get('/api/state')).json()).data.state
 expect(stored.nutritionRecipes[0].items[0].grams).toBe(200)
 await page.getByRole('button',{name:'更新搭配',exact:true}).click()
 await expect.poll(async()=>((await (await page.request.get('/api/state')).json()).data.state.nutritionRecipes[0].items[0].grams)).toBe(100)
 await page.getByRole('button',{name:'移除水煮鸡蛋',exact:true}).click()
 await expect(page.locator('[data-nutrient=fiber]')).toContainText('未提供数值')
 const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:/导出计算清单/}).click()
 const download=await downloadPromise,file=await download.path()
 expect(download.suggestedFilename()).toBe('foodmoment-nutrition.txt')
 const text=await readFile(file!,'utf8');expect(text).toContain('膳食纤维：未知');expect(text).toContain('钠：0 mg');expect(text).toContain('每100g热量：100 kcal')
 await page.getByRole('button',{name:'删除搭配测试组合早餐',exact:true}).click()
 await page.getByRole('button',{name:'确认删除搭配',exact:true}).click()
 await expect.poll(async()=>((await (await page.request.get('/api/state')).json()).data.state.nutritionRecipes||[]).length).toBe(0)
 expect((await (await page.request.get('/api/state')).json()).data.state.meals).toEqual(before.meals)
 expect(errors).toEqual([])
})

test('营养记录按日期餐次计算，空日期不虚构摄入，手机可用',async({page})=>{
 await page.goto('/#/nutrition');await page.getByRole('button',{name:'记录汇总',exact:true}).click()
 const today=await page.getByLabel('记录日期',{exact:true}).inputValue()
 await expect(page.getByText('这一天的所选餐次还没有记录。')).toBeVisible()
 const data=(await (await page.request.get('/api/state')).json()).data
 data.state.meals=[{id:'n1',date:today,slot:'午餐',foodId:'chicken',grams:200,cost:18},{id:'n2',date:today,slot:'晚餐',foodId:'noodle',grams:100,cost:12}]
 expect((await page.request.put('/api/state',{data})).ok()).toBe(true)
 await page.reload();await page.getByRole('button',{name:'记录汇总',exact:true}).click()
 await expect(page.locator('[data-nutrient=kcal] strong')).toContainText('417')
 await page.getByLabel('查看餐次',{exact:true}).selectOption('午餐')
 await expect(page.locator('[data-nutrient=kcal] strong')).toContainText('312')
 await expect(page.locator('.nutrition-record-list article')).toHaveCount(1)
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.getByLabel('记录日期',{exact:true}).fill('2020-01-01')
 await expect(page.getByText('这一天的所选餐次还没有记录。')).toBeVisible()
 await expect(page.locator('[data-nutrient=kcal]')).toHaveCount(0)
 expect((await (await page.request.get('/api/state')).json()).data.state.meals).toHaveLength(2)
})
