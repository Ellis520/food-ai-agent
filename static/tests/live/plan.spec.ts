import {test,expect} from '../completeProfile'
test.skip(process.env.RUN_LIVE_SERVICES!=='1','Real Qwen plan generation is opt-in')
test('真实千问计划从聊天带入规划页，编辑后确认保存并刷新恢复',async({page})=>{
 await page.goto('/#/chat')
 await page.getByRole('textbox',{name:'聊天消息'}).fill('请调用饮食规划工具，按今天45元预算、不限口味，生成一日三餐。')
 const responsePromise=page.waitForResponse(r=>r.url().endsWith('/api/chat')&&r.request().method()==='POST')
 await page.getByRole('button',{name:'发送消息'}).click()
 const response=await responsePromise
 expect(response.status()).toBe(200)
 const message=(await response.json()).data
 expect(message.planItems).toHaveLength(3)
 await expect(page.locator('.plan-summary .between')).toHaveCount(3)
 await page.locator('.structured-card a').click()
 await expect(page.locator('.plan-card')).toHaveCount(3)
 const first=page.locator('.plan-card input[type=number]').first()
 await expect(first).toHaveValue(String(message.planItems[0].grams))
 await first.fill('280')
 expect((await (await page.request.get('/api/state')).json()).data.state.plans).toEqual({})
 await page.getByRole('button',{name:'保存这份计划'}).click()
 await expect.poll(async()=>{const result=await (await page.request.get('/api/state')).json();return result.data.state.plans[message.planDate]?.[0].grams}).toBe(280)
 await page.goto('/#/plan');await page.reload()
 await expect(page.locator('.plan-card input[type=number]').first()).toHaveValue('280')
 await page.screenshot({path:'../plan-preview.png'})
 await page.locator('.plan-card input[type=number]').first().fill('333')
 expect((await (await page.request.get('/api/state')).json()).data.state.plans[message.planDate][0].grams).toBe(280)
 await page.locator('.week-tabs button').nth(1).click()
 await page.locator('.week-tabs button').first().click()
 await expect(page.locator('.plan-card input[type=number]').first()).toHaveValue('280')
 await page.setViewportSize({width:390,height:844})
 await expect.poll(()=>page.locator('.sidebar').evaluate(el=>el.getBoundingClientRect().right)).toBeLessThanOrEqual(0)
 await page.evaluate(()=>{(document.activeElement as HTMLElement)?.blur();window.scrollTo(0,0)})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:'../plan-mobile-preview.png',fullPage:true})
})
