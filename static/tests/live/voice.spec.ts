import {test,expect} from '../completeProfile'
import {readFileSync} from 'node:fs'
test.skip(!process.env.ASR_TEST_WAV,'Set ASR_TEST_WAV to the official 16kHz PCM WAV example')
test.beforeEach(async({page})=>{
 const sample=readFileSync(process.env.ASR_TEST_WAV!)
 // Test-only synthetic stream: never requests or reads the user's real microphone.
 await page.addInitScript((encoded:string)=>{
  Object.defineProperty(navigator.mediaDevices,'getUserMedia',{value:async()=>{
   const bytes=Uint8Array.from(atob(encoded),c=>c.charCodeAt(0))
   const audio=new AudioContext({sampleRate:16000})
   const source=audio.createBufferSource()
   source.buffer=await audio.decodeAudioData(bytes.buffer)
   const destination=audio.createMediaStreamDestination()
   source.connect(destination)
   source.onended=()=>{(window as Window&{asrSampleEnded?:boolean}).asrSampleEnded=true}
   await audio.resume();source.start(audio.currentTime+0.5)
   return destination.stream
  }})
 },sample.toString('base64'))
})
test('公开示例音频经过浏览器PCM处理与真实FunASR后填入聊天框',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 const touch=await page.context().newCDPSession(page)
 await touch.send('Emulation.setTouchEmulationEnabled',{enabled:true})
 await page.goto('/#/chat')
 const mic=page.getByRole('button',{name:'按住语音输入',exact:true})
 await mic.evaluate(button=>button.scrollIntoView({block:'center',behavior:'instant'}))
 const bounds=(await mic.boundingBox())!
 const point={x:bounds.x+bounds.width/2,y:bounds.y+bounds.height/2}
 expect(await mic.evaluate((button,{x,y})=>button.contains(document.elementFromPoint(x,y)),point)).toBe(true)
 await touch.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[point]})
 await expect(page.getByText('正在录音 · 松开结束')).toBeVisible()
 await expect(page.getByText('FunASR 2-Pass 语音输入')).toHaveCount(0)
 await expect.poll(()=>page.getByRole('textbox',{name:'聊天消息'}).inputValue(),{timeout:10000}).not.toBe('')
 const firstDraft=await page.getByRole('textbox',{name:'聊天消息'}).inputValue()
 await expect.poll(async()=>(await page.getByRole('textbox',{name:'聊天消息'}).inputValue()).length,{timeout:10000}).toBeGreaterThan(firstDraft.length)
 expect(await page.getByRole('textbox',{name:'聊天消息'}).inputValue()).toContain(firstDraft)
 await expect(page.getByRole('textbox',{name:'聊天消息'})).toHaveJSProperty('readOnly',true)
 await expect(page.getByRole('button',{name:'发送消息'})).toBeDisabled()
 await expect.poll(()=>page.evaluate(()=>(window as Window&{asrSampleEnded?:boolean}).asrSampleEnded),{timeout:15000}).toBe(true)
 await touch.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
 await expect(page.getByText('正在校正语音…')).toBeVisible()
 await expect(page.getByRole('textbox',{name:'聊天消息'})).not.toHaveValue('',{timeout:45000})
 await expect(page.getByRole('textbox',{name:'聊天消息'})).toHaveJSProperty('readOnly',false,{timeout:45000})
 await expect(page.locator('.message.user')).toHaveCount(0)
})

test('取消录音恢复原稿，后续结果不会覆盖原稿',async({page})=>{
 await page.goto('/#/chat')
 const input=page.getByRole('textbox',{name:'聊天消息'})
 await input.fill('今天午餐：')
 await page.getByRole('button',{name:'按住语音输入',exact:true}).focus()
 await page.keyboard.down('Space')
 await expect.poll(async()=>(await input.inputValue()).length,{timeout:15000}).toBeGreaterThan('今天午餐：'.length)
 await page.keyboard.press('Escape')
 await page.keyboard.up('Space')
 await expect(input).toHaveValue('今天午餐：')
 await expect(input).toHaveJSProperty('readOnly',false)
 await input.fill('手动修改后的原稿')
 await expect.poll(()=>page.evaluate(()=>(window as Window&{asrSampleEnded?:boolean}).asrSampleEnded),{timeout:15000}).toBe(true)
 await expect(input).toHaveValue('手动修改后的原稿')
 await expect(page.locator('.message.user')).toHaveCount(0)
})

test('饮食小贴士复用真实流式识别，校正后可编辑且不自动提问',async({page})=>{
 let calls=0;await page.route('**/api/safety/ask',route=>{calls++;return route.abort()})
 await page.goto('/#/language')
 const input=page.getByRole('textbox',{name:'饮食安全问题',exact:true})
 await input.fill('我想问：')
 await page.getByRole('button',{name:'按住语音提问',exact:true}).focus()
 await page.keyboard.down('Space')
 await expect.poll(async()=>(await input.inputValue()).length,{timeout:15000}).toBeGreaterThan('我想问：'.length)
 const first=await input.inputValue()
 await expect.poll(async()=>(await input.inputValue()).length,{timeout:15000}).toBeGreaterThan(first.length)
 await expect(page.getByRole('button',{name:'发送问题',exact:true})).toBeDisabled()
 await expect(input).toHaveJSProperty('readOnly',true)
 await expect.poll(()=>page.evaluate(()=>(window as Window&{asrSampleEnded?:boolean}).asrSampleEnded),{timeout:15000}).toBe(true)
 await page.keyboard.up('Space')
 await expect(input).toHaveJSProperty('readOnly',false,{timeout:45000})
 await expect(input).toHaveValue(/^我想问：.+/)
 await input.fill('校正后我可以手动修改药名')
 await expect(page.getByRole('button',{name:'发送问题',exact:true})).toBeEnabled()
 await expect(page.getByRole('article',{name:'安全问答回复'})).toHaveCount(0)
 expect(calls).toBe(0)
})
